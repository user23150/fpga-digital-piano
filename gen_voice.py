# -*- coding: utf-8 -*-
"""生成 src/voice.v —— 单个声部 (正弦表 + 颤音 + 滑音 + 4种乐器预设)"""
import math
import os

N = 256
AMP = 32000
SINE = [int(round(math.sin(2 * math.pi * i / N) * AMP)) & 0xFFFF for i in range(N)]

o = []
a = o.append
a("`timescale 1ns/1ps")
a("// ============================================================================")
a("//  单个声部 (Voice): DDS + 乐器预设(波形+ADSR) + 力度 + 滑音 + 颤音")
a("//")
a("//  乐器预设 (preset):")
a("//    0 = 钢琴  : 锯齿波, 快起音, 中衰减, 50%延持, 中释放")
a("//    1 = 风琴  : 方波,   极快起音, 几乎不衰减, 95%延持, 快释放")
a("//    2 = 弦乐  : 锯齿波, 慢起音(120ms), 长延持, 长释放(像弓弦)")
a("//    3 = 木琴  : 三角波, 极快起音, 快速衰减到消失(打击感)")
a("//")
a("//  包络衰减用'指数'而不是线性: env - (env>>N), 听感更接近真实乐器")
a("// ============================================================================")
a("module voice (")
a("    input  wire        clk,")
a("    input  wire        rst_n,")
a("    input  wire        tick_sample,      // 48kHz 采样节拍")
a("    input  wire [31:0] fword,            // 目标频率控制字")
a("    input  wire        gate,             // 1 = 发声")
a("    input  wire [1:0]  preset,           // 乐器预设 0~3")
a("    input  wire [11:0] loud,             // 力度系数")
a("    input  wire signed [7:0] vib_lfo,    // 颤音 LFO")
a("    input  wire        vib_on,           // 颤音开关")
a("    input  wire        env_rst,          // 换音脉冲: 强制复位包络(否则音符会粘连)")
a("    output reg  [15:0] sample            // 输出采样")
a(");")
a("")
a("    // ---------------- 乐器预设参数 ----------------")
a("    // SUS: 延持电平 | ATK: 起音速率(移位) | DEC/REL: 指数衰减速率(移位)")
a("    wire [11:0] p_sus = (preset == 2'd0) ? 12'd2048 :   // 钢琴 50%")
a("                        (preset == 2'd1) ? 12'd3891 :   // 风琴 95%")
a("                        (preset == 2'd2) ? 12'd3277 :   // 弦乐 80%")
a("                                           12'd614;    // 木琴 15%(衰减后仍有轻音, 不会完全静音)")
a("")
a("    wire [3:0]  p_atk = (preset == 2'd0) ? 4'd6  :      // 钢琴 快")
a("                        (preset == 2'd1) ? 4'd5  :      // 风琴 极快")
a("                        (preset == 2'd2) ? 4'd11 :      // 弦乐 慢(约120ms)")
a("                                           4'd6;       // 木琴 快")
a("")
a("    wire [3:0]  p_dec = (preset == 2'd0) ? 4'd10 :      // 钢琴 中")
a("                        (preset == 2'd1) ? 4'd14 :      // 风琴 极慢")
a("                        (preset == 2'd2) ? 4'd11 :      // 弦乐 慢")
a("                                           4'd7;       // 木琴 快")
a("")
a("    wire [3:0]  p_rel = (preset == 2'd0) ? 4'd9  :      // 钢琴 中")
a("                        (preset == 2'd1) ? 4'd6  :      // 风琴 快")
a("                        (preset == 2'd2) ? 4'd12 :      // 弦乐 慢")
a("                                           4'd7;       // 木琴 快")
a("")
a("    // ---------------- 滑音: 当前频率向目标渐变 ----------------")
a("    localparam [31:0] GLIDE_STEP = 32'd900000;      // 快速到位(约0.3ms), 音头更干净")
a("    reg [31:0] cur_fw;")
a("")
a("    always @(posedge clk or negedge rst_n) begin")
a("        if (!rst_n) cur_fw <= 32'd0;")
a("        else if (tick_sample) begin")
a("            if (env_rst)")
a("                cur_fw <= fword;                // 换音: 立即到位")
a("            else if (cur_fw < fword - GLIDE_STEP)")
a("                cur_fw <= cur_fw + GLIDE_STEP;   // 快速滑音(约0.3ms)")
a("            else if (cur_fw > fword + GLIDE_STEP)")
a("                cur_fw <= cur_fw - GLIDE_STEP;")
a("            else")
a("                cur_fw <= fword;")
a("        end")
a("    end")
a("")
a("    // ---------------- 颤音调制 ----------------")
a("    wire signed [15:0] fhi      = cur_fw[31:16];")
a("    wire signed [31:0] vib_prod = fhi * $signed(vib_lfo);")
a("    wire signed [31:0] vib_del  = vib_prod >>> 7;")
a("    wire        [31:0] fw_final = vib_on ? (cur_fw + vib_del) : cur_fw;")
a("")
a("    // ---------------- DDS 相位累加 ----------------")
a("    reg [31:0] phase;")
a("    always @(posedge clk or negedge rst_n) begin")
a("        if (!rst_n) phase <= 32'd0;")
a("        else if (tick_sample)")
a("            phase <= gate ? (phase + fw_final) : 32'd0;")
a("    end")
a("")
a("    // ---------------- ADSR 包络 (指数曲线) ----------------")
a("    localparam [11:0] ENV_MAX = 12'd4095;")
a("    localparam [1:0]  E_IDLE = 2'd0, E_ATK = 2'd1, E_DEC = 2'd2, E_SUS = 2'd3;")
a("")
a("    reg [11:0] env;")
a("    reg [1:0]  env_st;")
a("    reg [2:0]  env_div;")
a("    wire       env_slow = (env_div == 3'd7);")
a("")
a("    always @(posedge clk or negedge rst_n) begin")
a("        if (!rst_n) begin")
a("            env     <= 12'd0;")
a("            env_st  <= E_IDLE;")
a("            env_div <= 3'd0;")
a("        end else if (tick_sample) begin")
a("            env_div <= (env_div == 3'd7) ? 3'd0 : env_div + 1'b1;")
a("            if (env_rst) begin")
a("                // ---- 换音: 包络立即归零, 让下一个音干净起音 ----")
a("                env    <= 12'd0;")
a("                env_st <= E_IDLE;")
a("            end else if (!gate) begin")
a("                // ---------- 指数释放 ----------")
a("                if (env_st != E_IDLE && env_slow) begin")
a("                    if (env <= 12'd16) begin")
a("                        env    <= 12'd0;")
a("                        env_st <= E_IDLE;")
a("                    end else")
a("                        env <= env - (env >> p_rel) - 12'd1;")
a("                end")
a("            end else begin")
a("                case (env_st)")
a("                    E_IDLE: begin")
a("                        env    <= 12'd0;")
a("                        env_st <= E_ATK;")
a("                    end")
a("                    E_ATK: begin")
a("                        if (env >= ENV_MAX - (ENV_MAX >> p_atk)) begin")
a("                            env    <= ENV_MAX;")
a("                            env_st <= E_DEC;")
a("                        end else")
a("                            env <= env + (ENV_MAX >> p_atk) + 12'd1;")
a("                    end")
a("                    E_DEC: begin")
a("                        if (env_slow) begin")
a("                            if (env <= p_sus + 12'd16) begin")
a("                                env    <= p_sus;")
a("                                env_st <= E_SUS;")
a("                            end else")
a("                                env <= env - (env >> p_dec) - 12'd1;")
a("                        end")
a("                    end")
a("                    E_SUS:  env <= p_sus;")
a("                    default: env_st <= E_ATK;")
a("                endcase")
a("            end")
a("        end")
a("    end")
a("")
a("    // ---------------- 正弦查找表 (256 点, ±32000) ----------------")
a("    reg [15:0] rom [0:255];")
a("    initial begin")
for i in range(0, N, 8):
    seg = SINE[i:i + 8]
    a("        " + " ".join(f"rom[{i+j:3d}] = 16'h{v:04X};" for j, v in enumerate(seg)))
a("    end")
a("")
a("    // ---------------- 4 种波形 ----------------")
a("    wire signed [15:0] w_sine   = rom[phase[31:24]];")
a("    wire signed [15:0] w_square = phase[31] ? 16'sh6000 : 16'shA000;")
a("    wire signed [15:0] w_tri    = phase[31] ? ~phase[30:15] : phase[30:15];")
a("    wire signed [15:0] w_saw    = phase[31:16];")
a("")
a("    // 预设 -> 波形: 0=正弦(默认,最空灵) 1=三角(柔和) 2=锯齿(明亮) 3=方波(粗犷)")
a("    wire signed [15:0] wave_out = (preset == 2'd0) ? w_sine   :")
a("                                  (preset == 2'd1) ? w_tri    :")
a("                                  (preset == 2'd2) ? w_saw    : w_square;")
a("")
a("    // ---------------- 起音瞬态噪声 ----------------")
a("    //   真实乐器起音都有短暂的'咔/气'声(钢琴锤击、吉他拨弦、长笛气声)")
a("    //   这里用 LFSR 伪随机噪声, 在起音瞬间混入, 并在约 30ms 内指数衰减")
a("    reg  [15:0] lfsr;")
a("    reg  [7:0]  trk_env;")
a("    reg         gate_p;")
a("")
a("    always @(posedge clk or negedge rst_n) begin")
a("        if (!rst_n) begin")
a("            lfsr    <= 16'hACE1;")
a("            trk_env <= 8'd0;")
a("            gate_p  <= 1'b0;")
a("        end else if (tick_sample) begin")
a("            lfsr   <= {lfsr[14:0], lfsr[15] ^ lfsr[13] ^ lfsr[12] ^ lfsr[10]};")
a("            gate_p <= gate;")
a("            if (gate && !gate_p)")
a("                trk_env <= 8'd0;                       // 关闭起音白噪声(听感滋滋/沙沙)")
a("            else if (trk_env > 8'd2)")
a("                trk_env <= trk_env - (trk_env >> 3) - 1'b1;   // 指数衰减")
a("            else")
a("                trk_env <= 8'd0;")
a("        end")
a("    end")
a("")
a("    wire signed [15:0] noise = {lfsr[15], lfsr[13], lfsr[11], lfsr[9],")
a("                                lfsr[7],  lfsr[5],  lfsr[3],  lfsr[1], 8'b0};")
a("    wire signed [23:0] trk_mul   = noise * $signed({1'b0, trk_env});")
a("    wire signed [15:0] trk_noise = trk_mul[23:8];")
a("")
a("    wire signed [16:0] wave_sum = $signed(wave_out) + trk_noise;")
a("    wire signed [15:0] wave_trk =")
a("        (wave_sum > 17'sd32767)  ? 16'sh7FFF :")
a("        (wave_sum < -17'sd32768) ? 16'sh8000 : wave_sum[15:0];")
a("")
a("    // ---------------- 包络 x 力度 x 波形 ----------------")
a("    wire [23:0] env_vol    = env * loud;")
a("    wire [11:0] env_final  = env_vol[23:12];")
a("    wire signed [27:0] prod = wave_trk * $signed({1'b0, env_final});")
a("")
a("    always @(posedge clk or negedge rst_n) begin")
a("        if (!rst_n)            sample <= 16'd0;")
a("        else if (tick_sample)  sample <= $signed(prod[27:12]) >>> 1;   // 降半, 给混音留余量(防削顶)")
a("    end")
a("")
a("endmodule")

with open(os.path.join(os.path.dirname(os.path.abspath(__file__)), "src", "voice.v"), "w", encoding="utf-8", newline="\n") as fp:
    fp.write("\n".join(o) + "\n")
print("已生成 src/voice.v (4 种乐器预设 + 指数 ADSR)")
